-- Create a CTE (temporary result set) named sells_cte
WITH sells_cte AS (
  SELECT
    *,
    
    -- Find the first purchase date for each unique customer
    FORMAT_DATE('%d.%m.%Y', MIN(order_date) OVER (PARTITION BY client_id)) AS first_date,
    
    -- Find the last purchase date for each unique customer
    FORMAT_DATE('%d.%m.%Y', MAX(order_date) OVER (PARTITION BY client_id)) AS last_date,
    
    -- Calculate the total number of unique orders per customer
    COUNT(DISTINCT order_id) OVER (PARTITION BY client_id) AS client_order,
    
    -- Calculate total revenue generated by each customer
    SUM(sum_grn) OVER (PARTITION BY client_id) AS client_revenue,
    
    -- Calculate purchasing interval (handling division by zero)
    ROUND(
      SAFE_DIVIDE(
        DATE_DIFF(MAX(order_date) OVER (PARTITION BY client_id), MIN(order_date) OVER (PARTITION BY client_id), MONTH),
        NULLIF(COUNT(DISTINCT order_id) OVER (PARTITION BY client_id) - 1, 0)
      ),
      1
    ) AS client_interval_null,
    
    -- Core logic for purchasing interval calculation:
    -- If a customer has more than 1 purchase, calculate the specific interval
    -- If only one purchase, apply the average interval of all customers who bought >1 time
    IF(
      COUNT(DISTINCT order_id) OVER (PARTITION BY client_id) > 1,
      
      -- Interval formula: (last purchase date - first purchase date) / (total orders - 1)
      ROUND(
        SAFE_DIVIDE(
          DATE_DIFF(MAX(order_date) OVER (PARTITION BY client_id), MIN(order_date) OVER (PARTITION BY client_id), MONTH),
          COUNT(DISTINCT order_id) OVER (PARTITION BY client_id) - 1
        ),
        1
      ),
      
      -- Average interval for all multi-purchase customers
      (
        SELECT ROUND(AVG(interval_val), 1)
        FROM (
          SELECT
            client_id,
            SAFE_DIVIDE(
              DATE_DIFF(MAX(order_date) OVER (PARTITION BY client_id), MIN(order_date) OVER (PARTITION BY client_id), MONTH),
              COUNT(DISTINCT order_id) OVER (PARTITION BY client_id) - 1
            ) AS interval_val
          FROM STA.sells_calc
        )
        WHERE interval_val IS NOT NULL
      )
    ) AS client_interval,
    
    -- Calculate Average Order Value (AOV) per customer
    ROUND(
      SAFE_DIVIDE(
        SUM(sum_grn) OVER (PARTITION BY client_id),
        COUNT(DISTINCT order_id) OVER (PARTITION BY client_id)
      ),
      2
    ) AS client_check

  FROM `gold-contact-440009-h4.STA.sells_calc`
),

rfm AS (
  -- Core SELECT: assign FrequencyScore based on the total order count
  SELECT
    *,
    
    -- FrequencyScore assignment logic:
    -- 1 order → 1 point
    -- 2–10 orders → 2 points
    -- More than 10 orders → 3 points
    CASE
      WHEN client_order = 1 THEN 1
      WHEN client_order BETWEEN 2 AND 10 THEN 2
      WHEN client_order > 10 THEN 3
    END AS FrequencyScore,
    
    -- RecencyScore calculation: evaluate how recent the customer's last purchase is
    -- Uses a fixed reporting baseline date — March 1, 2022
    CASE
      WHEN DATE_DIFF(DATE '2022-03-01', PARSE_DATE('%d.%m.%Y', last_date), MONTH) <= 6 THEN 3
      WHEN DATE_DIFF(DATE '2022-03-01', PARSE_DATE('%d.%m.%Y', last_date), MONTH) <= 24 THEN 2
      WHEN DATE_DIFF(DATE '2022-03-01', PARSE_DATE('%d.%m.%Y', last_date), MONTH) > 24 THEN 1
    END AS RecencyScore,
    
    -- MonetaryScore calculation: evaluate customer financial value based on cumulative Lifetime Value (LTV)
    CASE
      WHEN client_revenue > 20000 THEN 3
      WHEN client_revenue BETWEEN 2000 AND 20000 THEN 2
      WHEN client_revenue < 2000 THEN 1
    END AS MonetaryScore

  FROM sells_cte
),

rfm_cod AS (
  SELECT 
    *,
    -- Formulate the unified three-digit RFM code string (e.g., 3 + 2 + 1 = "321")
    CONCAT(CAST(RecencyScore AS STRING), CAST(FrequencyScore AS STRING), CAST(MonetaryScore AS STRING)) AS RFM_Code
  FROM rfm
)
 
SELECT 
  *,
  -- RFM_Group derivation: categorize customers into business segments based on dynamic RFM patterns
  CASE
    -- 🟡 Passive Customers (High latency, lower engagement profiles)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) IN ("111", "122", "212", "221", "112", "121", "211") THEN "Passive"

    -- 💰 High-Yield Customers (High monetary metrics across varying frequency metrics)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) IN ("113", "123", "213", "223", "233", "323", "133") THEN "Monetary"

    -- 🟢 Stable Customers (Consistent purchasing habits over extended time horizons)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) IN ("222", "232") THEN "Stable"

    -- 🔁 Frequent Buyers (High purchase counts but lower financial margins)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) IN ("131", "132", "231") THEN "Frequent"

    -- 🕒 Recent Buyers (Newly acquired accounts with lower immediate frequency metrics)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) IN ("311", "312", "313", "321", "322", "331", "332") THEN "Recent"

    -- 👑 Top-Tier Value Customers (Maximum performance vectors across all RFM fields)
    WHEN CAST(RecencyScore * 100 + FrequencyScore * 10 + MonetaryScore AS STRING) = "333" THEN "VIP"
  END AS RFM_Group
FROM rfm_cod;
